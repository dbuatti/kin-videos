"use client";

import React, { useMemo } from "react";
import { useNavigate } from "react-router-dom";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import {
  ArrowLeft, Scissors, Terminal, Copy, Info, AlertTriangle, Download, FileText,
} from "lucide-react";
import { showSuccess, showError } from "@/utils/toast";
import { MadeWithDyad } from "@/components/made-with-dyad";
import { useJobLessons } from "@/hooks/use-job-lessons";
import { VERIFIED_LESSON_ORDER } from "@/utils/filenames";

const Stitcher = () => {
  const navigate = useNavigate();
  const { data: lessons } = useJobLessons();

  const ordered = useMemo(() => {
    if (!lessons) return [];
    const rank = new Map(VERIFIED_LESSON_ORDER.map((u, i) => [u, i]));
    return [...lessons]
      .filter((l) => l.video_url)
      .sort((a, b) => {
        const ra = rank.has(a.lesson_url) ? rank.get(a.lesson_url)! : Number.MAX_SAFE_INTEGER;
        const rb = rank.has(b.lesson_url) ? rank.get(b.lesson_url)! : Number.MAX_SAFE_INTEGER;
        if (ra !== rb) return ra - rb;
        return new Date(a.created_at).getTime() - new Date(b.created_at).getTime();
      });
  }, [lessons]);

  const manifestJson = useMemo(
    () => JSON.stringify(ordered.map((l, i) => ({
      i: i + 1,
      category: l.category,
      title: l.title,
      page_url: l.lesson_url,
      video_url: l.video_url,
    })), null, 2),
    [ordered]
  );

  const manifestB64 = useMemo(() => {
    try { return btoa(unescape(encodeURIComponent(manifestJson))); } catch { return ""; }
  }, [manifestJson]);

  const pythonScript = useMemo(() => {
    if (!ordered.length || !manifestB64) return "";
    return `#!/usr/bin/env python3
"""stitch_fnh.py — stitch the FNH course videos in syllabus order.

Generated by the Kin-Videos Stitcher from the verified lesson list.
Run:  python3 stitch_fnh.py --root "/path/to/FNH" --dry-run
      python3 stitch_fnh.py --root "/path/to/FNH"
"""
import argparse, base64, json, os, re, subprocess, sys, unicodedata, difflib

MANIFEST = json.loads(base64.b64decode("""${manifestB64}""").decode("utf-8"))

SKIP = {"_DUPLICATES", "_REVIEW", "_CORPUS", "_REFERENCE_APP", "PRINTING", "_AUDIO", "node_modules", ".git"}
MEDIA_EXT = {".mp4", ".m4a", ".mp3", ".mov", ".m4v", ".mkv"}

def norm(s):
    s = unicodedata.normalize("NFKD", str(s or "")).lower()
    s = re.sub(r"\\.(mp4|m4a|mp3|mov|m4v|mkv)$", "", s)
    s = re.sub(r"^\\(\\d+\\)\\s*", "", s)
    s = re.sub(r"[^a-z0-9]+", " ", s)
    return " ".join(s.split())

STOP = {"lecture","demo","in","class","and","the","of","a","an","assessment","procedure","muscle","tests","test","reflex","correction","review","part","video","full","with","for","to","introduction","overview"}

def tokens(s):
    return {w for w in norm(s).split() if w not in STOP}

def score(title, filename):
    t = tokens(title); f = tokens(filename)
    if not t or not f:
        return 0.0
    inter = len(t & f)
    coverage = inter / len(t)
    jaccard = inter / len(t | f)
    s = coverage * 0.72 + jaccard * 0.28
    if norm(title) and norm(title) in norm(filename):
        s = max(s, 0.95)
    return s

def walk(root):
    out = []
    for dp, dn, fn in os.walk(root):
        dn[:] = [d for d in dn if d not in SKIP]
        for f in fn:
            if os.path.splitext(f)[1].lower() in MEDIA_EXT:
                out.append(os.path.join(dp, f))
    return out

def esc_ffmpeg_path(p):
    return p.replace("'", "'\\\\''")

def ffprobe_duration(path):
    try:
        r = subprocess.run(["ffprobe","-v","error","-show_entries","format=duration","-of","default=noprint_wrappers=1:nokey=1",path],
                           capture_output=True, text=True, timeout=30)
        v = r.stdout.strip()
        return float(v) if v else None
    except Exception:
        return None

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.expanduser("~/Library/CloudStorage/Dropbox/Wellness, Meditation and Kinesiology/FNH"))
    ap.add_argument("--out", default=None)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--audio", action="store_true")
    args = ap.parse_args()

    root = os.path.expanduser(args.root)
    outdir = args.out or root
    os.makedirs(outdir, exist_ok=True)

    files = walk(root)
    print("Scanned " + str(len(files)) + " media files under " + root)

    matches = []
    for item in MANIFEST:
        best, bestScore = None, 0.0
        for f in files:
            s = score(item["title"], os.path.basename(f))
            if s > bestScore:
                bestScore, best = s, f
        if best is not None and bestScore >= 0.66:
            matches.append((item, best, bestScore))
        else:
            matches.append((item, None, bestScore))

    path_to_items = {}
    for item, fp, sc in matches:
        if fp:
            path_to_items.setdefault(fp, []).append(item["title"])

    ordered = []
    for item, fp, sc in matches:
        if fp is None:
            print("MISSING  " + item["title"] + "  (best score " + ("%.2f" % sc) + ")")
            continue
        if len(path_to_items.get(fp, [])) > 1 and fp in [m[1] for m in ordered]:
            print("SHARED   " + item["title"] + "  -> already used for another lesson (skipped)")
            continue
        ordered.append((item, fp, sc))
        print("matched  " + item["title"] + "  <-  " + os.path.basename(fp) + "  (" + ("%.2f" % sc) + ")")

    join_path = os.path.join(outdir, "join_list.txt")
    with open(join_path, "w") as fh:
        for item, fp, sc in ordered:
            fh.write("file '" + esc_ffmpeg_path(fp) + "'\\n")

    missing_path = os.path.join(outdir, "stitch_missing.tsv")
    with open(missing_path, "w") as fh:
        fh.write("module\\ttitle\\tpage_url\\tbest_score\\n")
        for item, fp, sc in matches:
            if fp is None:
                fh.write(item["category"] + "\\t" + item["title"] + "\\t" + item["page_url"] + "\\t" + ("%.2f" % sc) + "\\n")

    chapters_path = os.path.join(outdir, "chapters.txt")
    if ordered:
        lines = [";FFMETADATA1"]
        cursor = 0.0
        for item, fp, sc in ordered:
            dur = ffprobe_duration(fp)
            if dur is None:
                dur = 0.0
            start = int(cursor * 1000)
            end = int((cursor + dur) * 1000)
            lines.append("[CHAPTER]")
            lines.append("TIMEBASE=1/1000")
            lines.append("START=" + str(start))
            lines.append("END=" + str(end))
            lines.append("title=" + item["title"])
            cursor += dur
        with open(chapters_path, "w") as fh:
            fh.write("\\n".join(lines) + "\\n")

    print("")
    print("Wrote " + str(len(ordered)) + " entries -> " + join_path)
    print("Missing: " + str(sum(1 for m in matches if m[1] is None)) + " -> " + missing_path)
    print("Chapters -> " + chapters_path)

    if args.dry_run:
        print("\\nDry run: skipping ffmpeg.")
        return

    out_name = "FNH_Full_Course_Audio.mp3" if args.audio else "FNH_Full_Course_Stitched.mp4"
    out_file = os.path.join(outdir, out_name)

    cmd = ["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", join_path]
    if os.path.exists(chapters_path) and not args.audio:
        cmd += ["-i", chapters_path, "-map", "0", "-map_metadata", "1"]
    if args.audio:
        cmd += ["-vn", "-acodec", "libmp3lame", "-q:a", "2"]
    else:
        cmd += ["-c", "copy"]
    cmd.append(out_file)

    print("\\nRunning: " + " ".join(cmd))
    r = subprocess.run(cmd)
    if r.returncode != 0:
        print("\\nCopy failed - retrying with re-encode:", file=sys.stderr)
        cmd2 = ["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", join_path]
        if os.path.exists(chapters_path) and not args.audio:
            cmd2 += ["-i", chapters_path, "-map", "0", "-map_metadata", "1"]
        if args.audio:
            cmd2 += ["-vn", "-acodec", "libmp3lame", "-q:a", "2"]
        else:
            cmd2 += ["-c:v", "libx264", "-crf", "18", "-preset", "veryfast", "-c:a", "aac"]
        cmd2.append(out_file)
        subprocess.run(cmd2)

if __name__ == "__main__":
    main()
`;
  }, [ordered, manifestB64]);

  const copyScript = () => {
    if (!pythonScript) { showError("Import/archive lessons first."); return; }
    navigator.clipboard.writeText(pythonScript).then(
      () => showSuccess("Stitch script copied!"),
      () => showError("Copy failed")
    );
  };

  const downloadScript = () => {
    if (!pythonScript) { showError("Import/archive lessons first."); return; }
    const blob = new Blob([pythonScript], { type: "text/x-python" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = "stitch_fnh.py";
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(a.href), 1000);
    showSuccess("stitch_fnh.py downloaded");
  };

  const copyManifest = () => {
    if (!ordered.length) { showError("No lessons."); return; }
    navigator.clipboard.writeText(manifestJson).then(
      () => showSuccess("Manifest copied!"),
      () => showError("Copy failed")
    );
  };

  return (
    <div className="min-h-screen bg-background p-6 sm:p-12 max-w-4xl mx-auto w-full">
      <header className="flex items-center space-x-4 mb-12">
        <Button variant="ghost" size="icon" onClick={() => navigate("/")} className="rounded-full hover:bg-white/5 text-slate-400">
          <ArrowLeft className="w-5 h-5" />
        </Button>
        <div>
          <h1 className="text-3xl font-black text-white tracking-tight flex items-center">
            <Scissors className="w-6 h-6 mr-3 text-primary" />
            Stitcher
          </h1>
          <p className="text-xs text-slate-500 font-bold uppercase tracking-widest mt-1">
            FFmpeg · syllabus order · {ordered.length} video lessons
          </p>
        </div>
      </header>

      <main className="space-y-8">
        {!ordered.length ? (
          <Card className="border-white/5 bg-slate-900/40 backdrop-blur-xl rounded-[2rem] p-8 text-center text-slate-400">
            No video lessons yet. Archive or import the course first, then come back.
          </Card>
        ) : (
          <>
            <Card className="border-primary/20 bg-primary/5 backdrop-blur-xl rounded-[2.5rem] overflow-hidden border-2">
              <CardContent className="p-8 sm:p-12 flex flex-col md:flex-row items-center justify-between gap-8">
                <div className="space-y-3 text-center md:text-left">
                  <h3 className="text-2xl font-black text-white tracking-tight">Ordered stitch plan</h3>
                  <p className="text-slate-400 text-sm max-w-md leading-relaxed">
                    A Python script that walks your FNH folder, matches each lesson to a file by title
                    (fuzzy, so messy filenames still work), builds <code className="bg-white/5 px-1 rounded">join_list.txt</code> in
                    syllabus order, generates chapter markers from real durations, and runs ffmpeg.
                    Duplicate files are detected and skipped.
                  </p>
                  <p className="text-[11px] text-slate-500">
                    {ordered.length} lessons · {new Set(ordered.map((l) => l.category)).size} modules
                  </p>
                </div>
                <div className="flex flex-col gap-3 shrink-0">
                  <Button onClick={downloadScript} className="bg-primary hover:bg-primary/90 text-white rounded-2xl px-8 py-6 h-auto font-black shadow-2xl shadow-primary/20">
                    <Download className="w-5 h-5 mr-2" /> Download stitch_fnh.py
                  </Button>
                  <Button onClick={copyScript} variant="outline" className="border-white/10 bg-white/5 text-slate-300 hover:bg-white/10 rounded-xl h-12 px-6 font-bold">
                    <Copy className="w-4 h-4 mr-2" /> Copy script
                  </Button>
                  <Button onClick={copyManifest} variant="outline" className="border-white/10 bg-white/5 text-slate-300 hover:bg-white/10 rounded-xl h-12 px-6 font-bold">
                    <FileText className="w-4 h-4 mr-2" /> Copy manifest JSON
                  </Button>
                </div>
              </CardContent>
            </Card>

            <Card className="border-white/5 bg-slate-900/40 backdrop-blur-xl rounded-[2rem] overflow-hidden">
              <CardHeader className="border-b border-white/5 py-6">
                <CardTitle className="text-sm font-black uppercase tracking-widest text-indigo-400 flex items-center">
                  <Terminal className="w-5 h-5 mr-2" />
                  Run it
                </CardTitle>
              </CardHeader>
              <CardContent className="p-8 space-y-4">
                <div className="space-y-2">
                  <p className="text-[10px] font-black text-slate-500 uppercase tracking-widest">1. Dry run first (no ffmpeg, just lists matches + missing)</p>
                  <div className="flex items-center justify-between bg-black/20 p-4 rounded-xl border border-white/5">
                    <code className="text-primary font-mono text-xs truncate mr-4">python3 stitch_fnh.py --root "/Users/danielebuatti/Library/CloudStorage/Dropbox/Wellness, Meditation and Kinesiology/FNH" --dry-run</code>
                    <Button variant="ghost" size="sm" onClick={() => { navigator.clipboard.writeText('python3 stitch_fnh.py --root "/Users/danielebuatti/Library/CloudStorage/Dropbox/Wellness, Meditation and Kinesiology/FNH" --dry-run'); showSuccess("Copied"); }}><Copy className="w-4 h-4" /></Button>
                  </div>
                </div>
                <div className="space-y-2">
                  <p className="text-[10px] font-black text-slate-500 uppercase tracking-widest">2. Stitch video + chapters</p>
                  <div className="flex items-center justify-between bg-black/20 p-4 rounded-xl border border-white/5">
                    <code className="text-primary font-mono text-xs truncate mr-4">python3 stitch_fnh.py --root "/Users/danielebuatti/Library/CloudStorage/Dropbox/Wellness, Meditation and Kinesiology/FNH"</code>
                    <Button variant="ghost" size="sm" onClick={() => { navigator.clipboard.writeText('python3 stitch_fnh.py --root "/Users/danielebuatti/Library/CloudStorage/Dropbox/Wellness, Meditation and Kinesiology/FNH"'); showSuccess("Copied"); }}><Copy className="w-4 h-4" /></Button>
                  </div>
                </div>
                <div className="space-y-2">
                  <p className="text-[10px] font-black text-slate-500 uppercase tracking-widest">3. Audio only (mp3)</p>
                  <div className="flex items-center justify-between bg-black/20 p-4 rounded-xl border border-white/5">
                    <code className="text-emerald-400 font-mono text-xs truncate mr-4">python3 stitch_fnh.py --root "/Users/danielebuatti/Library/CloudStorage/Dropbox/Wellness, Meditation and Kinesiology/FNH" --audio</code>
                    <Button variant="ghost" size="sm" onClick={() => { navigator.clipboard.writeText('python3 stitch_fnh.py --root "/Users/danielebuatti/Library/CloudStorage/Dropbox/Wellness, Meditation and Kinesiology/FNH" --audio'); showSuccess("Copied"); }}><Copy className="w-4 h-4" /></Button>
                  </div>
                </div>
              </CardContent>
            </Card>

            <Card className="border-none bg-amber-500/10 rounded-[2.5rem] p-8 text-white">
              <div className="flex items-start space-x-6">
                <div className="bg-amber-500/20 p-3 rounded-2xl border border-amber-500/20">
                  <Info className="w-6 h-6 text-amber-500" />
                </div>
                <div className="text-sm text-slate-400">
                  <h4 className="font-black text-white mb-2 uppercase tracking-widest">Why this is better than the old commands</h4>
                  <p className="leading-relaxed">
                    The old <code className="bg-white/5 px-1.5 rounded text-amber-500">find | sort -V</code> stitched alphabetically by filename, which is not course order,
                    and <code className="bg-white/5 px-1.5 rounded text-amber-500">-c copy</code> fails when codecs differ. This script matches by title (so a file named
                    <code className="bg-white/5 px-1.5 rounded text-amber-500">(4) Direct Muscle Tests : (15) Upper Trapezius and SCM.mp4</code> still maps to the right lesson),
                    stitches in syllabus order, and falls back to a re-encode only if copy fails. Chapter markers come from ffprobe durations.
                  </p>
                  <div className="mt-6 flex items-center text-[10px] font-black text-amber-500 uppercase tracking-widest">
                    <AlertTriangle className="w-4 h-4 mr-2" />
                    Run --dry-run first to confirm matches and see which lessons are missing.
                  </div>
                </div>
              </div>
            </Card>
          </>
        )}
      </main>

      <footer className="mt-24 opacity-30">
        <MadeWithDyad />
      </footer>
    </div>
  );
};

export default Stitcher;
